"""Reference scores for the on-device parity test (frontend/integration_test).

    python -m wmg_train.parity_fixture runs/<ts>/model.pt

Generates the same deterministic synthetic signal as the Dart test (integer LCG noise plus
gated tones; no copyrighted audio), scores it with PyTorch at fp32 through the identical
pipeline (int16 -> /32768 -> level normalisation -> wmg_features windows), and writes the
expected per-window logits to frontend/integration_test/parity_expected.dart.
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path

import numpy as np
import torch

from . import features
from .score import load_model, normalize_level

SR, SECONDS = 32_000, 25
OUT = Path(__file__).resolve().parents[2] / "frontend" / "integration_test" / "parity_expected.dart"


def synthetic_pcm() -> np.ndarray:
    """Must match `syntheticPcm()` in the Dart test exactly."""
    n = SR * SECONDS
    out = np.empty(n, dtype=np.int16)
    state = 12345
    for i in range(n):
        state = (state * 1103515245 + 12345) % 2147483648
        noise = state / 2147483648 * 2 - 1
        t = i / SR
        gate = (i // 16000) % 2
        x = (0.25 * math.sin(2 * math.pi * 220 * t)
             + 0.15 * math.sin(2 * math.pi * 1760 * t) * gate
             + 0.10 * math.sin(2 * math.pi * 6000 * t) * (1 - gate)
             + 0.03 * noise)
        out[i] = int(round(max(-1.0, min(1.0, x)) * 32767))
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("model", type=Path)
    args = ap.parse_args()
    pcm = synthetic_pcm()
    mono = normalize_level(pcm.astype(np.float64) / 32768)
    windows = features.extract_windows(mono, SR)
    mel = torch.from_numpy(np.stack([w[2] for w in windows]).astype(np.float32))[:, None]
    model = load_model(args.model)
    with torch.no_grad():
        logits = model(mel)["ai_logit"].numpy().tolist()
    starts = [w[0] for w in windows]
    run = args.model.resolve().parent.name
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by `python -m wmg_train.parity_fixture` — do not edit.\n"
        f"const parityModelRun = '{run}';\n"
        f"const parityFeatureSpecHash = '{features.spec_hash()}';\n"
        f"const parityStarts = <double>{starts};\n"
        f"const parityLogits = <double>{[round(v, 5) for v in logits]};\n"
    )
    print(f"{len(logits)} windows, logits {np.round(logits, 3).tolist()} -> {OUT}")


if __name__ == "__main__":
    main()
