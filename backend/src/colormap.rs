pub struct Lut([[u8; 3]; 256]);

impl Lut {
    pub fn new(cmap: Colormap) -> Self {
        let mut lut = [[0u8; 3]; 256];
        for (i, px) in lut.iter_mut().enumerate() {
            let t = i as f64 / 255.0;
            let rgb = match cmap {
                Colormap::Gray => [t, t, t],
                Colormap::Viridis => poly(&VIRIDIS, t),
                Colormap::Magma => poly(&MAGMA, t),
                Colormap::Inferno => poly(&INFERNO, t),
            };
            *px = rgb.map(|c| (c.clamp(0.0, 1.0) * 255.0).round() as u8);
        }
        Self(lut)
    }

    /// Map `v` within `[vmin, vmax]` to RGB.
    pub fn map(&self, v: f64, vmin: f64, vmax: f64) -> [u8; 3] {
        let t = if vmax > vmin { (v - vmin) / (vmax - vmin) } else { 0.0 };
        let idx = (t.clamp(0.0, 1.0) * 255.0).round() as usize;
        self.0[idx]
    }
}

fn poly(c: &Coeffs, t: f64) -> [f64; 3] {
    let mut out = [0.0; 3];
    for (ch, o) in out.iter_mut().enumerate() {
        // Horner: c0 + t*(c1 + t*(c2 + ...))
        *o = c.iter().rev().fold(0.0, |acc, k| acc * t + k[ch]);
    }
    out
}
